//! Applying an update request to an entity.

/// A partial update that can be applied to an entity `E`.
///
/// `#[derive(Entity)]` implements `Patch<User> for UserUpdateRequest`: every
/// field that was supplied is copied onto the entity and the rest is left
/// alone. A field declared `Option<T>` is set to `Some(v)`; with `clearable`
/// (or the struct-level `patch` mode) an explicit `null` sets it to `None`.
///
/// ```
/// use folks::{Entity, Patch};
///
/// #[derive(Entity)]
/// struct Note {
///     #[entity(id)]
///     id: u32,
///     text: String,
/// }
///
/// let mut note = Note { id: 1, text: "old".into() };
/// NoteUpdateRequest::default().with_text("new").apply_to(&mut note);
/// assert_eq!(note.text, "new");
/// ```
pub trait Patch<E> {
    fn apply_to(self, target: &mut E);
}

/// Builds the update request that turns `old` into `new`.
///
/// Generated by `#[entity(diff)]`; needs `Clone + PartialEq` on the included
/// fields. A field declared `Option<T>` that became `None` cannot be expressed
/// unless it is `clearable` (then it becomes `Maybe::Null`).
pub trait Diff<E> {
    fn diff(old: &E, new: &E) -> Self;
}
